// features/ql_hit_marker/manifest.js
// =============================================================================
// QOLLOCK — Custom Hit Marker
// =============================================================================
// OWNS:        Root HUD classes qol-hm-* that select the hit marker rules in
//              styles/features/ql_feat_hit_marker.css (length, crit length,
//              thickness, spacing, colors, outline shadow, crit glow).
// DOES NOT OWN: Native hit marker panels and their show/hide logic (Valve);
//              the citadel_crosshair_hit_marker_duration on/off in the Console tab.
// DEPENDS ON:  QOL.core.FeatureRegistry, QOL.core.Scheduler
// CONFIG KEYS: ENABLE_CUSTOM_HITMARKER, CUSTOM_HITMARKER_SIZE, CUSTOM_HITMARKER_CRIT_SIZE,
//              CUSTOM_HITMARKER_THICKNESS, CUSTOM_HITMARKER_OFFSET, CUSTOM_HITMARKER_COLOR,
//              CUSTOM_HITMARKER_CRIT_COLOR, ENABLE_CUSTOM_HITMARKER_SHADOW,
//              ENABLE_CUSTOM_HITMARKER_HIDE_GLOW
// CSS:         styles/features/ql_feat_hit_marker.css, generated by
//              scripts/generate_hit_marker_css.js (ranges must match this file)
// PATTERN:     Class toggles only, no per-frame work. A 2s self-heal poll
//              re-applies the classes if the HUD root was replaced.
// =============================================================================

(function() {
    "use strict";
    var FR = QOL.core.FeatureRegistry;
    if (!FR) { $.Msg("[QOLLock] ql_hit_marker: FeatureRegistry not found — aborting"); return; }

    // Defaults equal the native hit marker (20px long, 2px thick, 40px from center),
    // so enabling the feature without changing a slider looks like the stock marker.
    var LENGTH = { min: 4, max: 40, def: 20 };
    var THICKNESS = { min: 1, max: 8, def: 2 };
    var OFFSET = { min: 4, max: 60, def: 40 };
    var PALETTE_MAX = 29;

    function _isTrue(v) { return v === true || v === 1 || String(v) === "true"; }

    function _int(v, lim) {
        var n = Math.round(Number(v));
        if (!isFinite(n)) n = lim.def;
        return n < lim.min ? lim.min : (n > lim.max ? lim.max : n);
    }

    function _palette(v) {
        var n = Math.round(Number(v));
        return (!isFinite(n) || n < 0 || n > PALETTE_MAX) ? 0 : n;
    }

    function desiredClasses(cfg) {
        var out = [
            "qol-hm",
            "qol-hm-len-" + _int(cfg.CUSTOM_HITMARKER_SIZE, LENGTH),
            "qol-hm-clen-" + _int(cfg.CUSTOM_HITMARKER_CRIT_SIZE, LENGTH),
            "qol-hm-th-" + _int(cfg.CUSTOM_HITMARKER_THICKNESS, THICKNESS),
            "qol-hm-off-" + _int(cfg.CUSTOM_HITMARKER_OFFSET, OFFSET),
            "qol-hm-col-" + _palette(cfg.CUSTOM_HITMARKER_COLOR),
            "qol-hm-ccol-" + _palette(cfg.CUSTOM_HITMARKER_CRIT_COLOR)
        ];
        if (_isTrue(cfg.ENABLE_CUSTOM_HITMARKER_SHADOW)) out.push("qol-hm-shadow");
        if (_isTrue(cfg.ENABLE_CUSTOM_HITMARKER_HIDE_GLOW)) out.push("qol-hm-noglow");
        return out;
    }

    FR.register({
        id: "ql_hit_marker",
        enableKey: "ENABLE_CUSTOM_HITMARKER",
        enabledByDefault: false,
        settings: [
            { key: "ENABLE_CUSTOM_HITMARKER", type: "toggle", default: false },
            { key: "ENABLE_CUSTOM_HITMARKER_SHADOW", type: "toggle", default: false },
            { key: "ENABLE_CUSTOM_HITMARKER_HIDE_GLOW", type: "toggle", default: false },
            { key: "CUSTOM_HITMARKER_SIZE", type: "slider", min: LENGTH.min, max: LENGTH.max, step: 1, default: LENGTH.def },
            { key: "CUSTOM_HITMARKER_CRIT_SIZE", type: "slider", min: LENGTH.min, max: LENGTH.max, step: 1, default: LENGTH.def },
            { key: "CUSTOM_HITMARKER_THICKNESS", type: "slider", min: THICKNESS.min, max: THICKNESS.max, step: 1, default: THICKNESS.def },
            { key: "CUSTOM_HITMARKER_OFFSET", type: "slider", min: OFFSET.min, max: OFFSET.max, step: 1, default: OFFSET.def },
            { key: "CUSTOM_HITMARKER_COLOR", type: "palette", default: 0 },
            { key: "CUSTOM_HITMARKER_CRIT_COLOR", type: "palette", default: 0 }
        ],
        create: function(ctx) {
            var _applied = [];
            var _root = null;
            var _loop = null;

            function _apply(cfg) {
                var root = $.GetContextPanel();
                if (!QOL.utils.IsPanelValid(root)) return;
                // A replaced root has none of our classes; forget what we applied to the old one.
                if (_root !== root) { _applied = []; _root = root; }
                var next = desiredClasses(cfg);
                var i;
                for (i = 0; i < _applied.length; i++) {
                    if (next.indexOf(_applied[i]) < 0) root.SetHasClass(_applied[i], false);
                }
                for (i = 0; i < next.length; i++) {
                    if (!root.BHasClass(next[i])) root.SetHasClass(next[i], true);
                }
                _applied = next;
            }

            function _clear() {
                if (_root && QOL.utils.IsPanelValid(_root)) {
                    for (var i = 0; i < _applied.length; i++) _root.SetHasClass(_applied[i], false);
                }
                _applied = [];
                _root = null;
            }

            return {
                onEnable: function() {
                    _apply(ctx.config.all());
                    var S = QOL.core.Scheduler;
                    _loop = S && S.createPollLoop ? S.createPollLoop(function() {
                        var root = $.GetContextPanel();
                        if (root !== _root || (QOL.utils.IsPanelValid(root) && !root.BHasClass("qol-hm"))) _apply(ctx.config.all());
                    }, 2, ctx.id) : null;
                },
                onDisable: function() {
                    if (_loop) { _loop.stop(); _loop = null; }
                    var S = QOL.core.Scheduler;
                    if (S && S.cancelAllForFeature) S.cancelAllForFeature(ctx.id);
                    _clear();
                },
                onSettingsChanged: function() { _apply(ctx.config.all()); }
            };
        }
    });
})();
