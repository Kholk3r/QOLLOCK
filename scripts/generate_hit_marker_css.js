#!/usr/bin/env node
// Generates panorama/styles/features/ql_feat_hit_marker.css.
//
// Panorama CSS cannot read a number from JavaScript, so every selectable hit marker
// value (length, thickness, spacing, color) is a static rule that the ql_hit_marker
// manifest switches on with a class on the HUD root (qol-hm-len-20, qol-hm-th-2, ...).
// The ranges below must match the ql_hit_marker manifest and the compact schema in
// ql_shared_presets.js; tests/hit_marker.test.js checks that all three agree.
//
//   node scripts/generate_hit_marker_css.js           write the stylesheet
//   node scripts/generate_hit_marker_css.js --check   exit 1 when the file is stale

"use strict";

const fs = require("fs");
const path = require("path");

const OUT = path.join(__dirname, "..", "panorama", "styles", "features", "ql_feat_hit_marker.css");

const RANGES = {
    length: { min: 4, max: 40 },
    thickness: { min: 1, max: 8 },
    offset: { min: 4, max: 60 }
};

// Palette index 0 keeps the native colors; 1..29 mirror QOL_WASH_COLOR_PALETTE.
const NATIVE_HIT_COLOR = "white";
const NATIVE_CRIT_COLOR = "yellow";
const NATIVE_CRIT_GLOW = "0px 0px 10px red";
const OUTLINE_SHADOW = "0px 0px 3px rgba(0, 0, 0, 0.6)";

// Each corner mirrors the native transform in base/ability_hud_elements/element_gun.css,
// with the native 40px translation replaced by the selected spacing.
const CORNERS = [
    { id: "TopLeftHitMarker", angle: 45, x: -1, y: -1 },
    { id: "TopRightHitMarker", angle: -45, x: 1, y: -1 },
    { id: "BottomLeftHitMarker", angle: -45, x: -1, y: 1 },
    { id: "BottomRightHitMarker", angle: 45, x: 1, y: 1 }
];

function loadPalette() {
    const src = fs.readFileSync(path.join(__dirname, "..", "panorama", "scripts", "ql_utils.js"), "utf8");
    const match = /const QOL_WASH_COLOR_PALETTE\s*=\s*\[([\s\S]*?)\]/.exec(src);
    if (!match) throw new Error("QOL_WASH_COLOR_PALETTE not found in ql_utils.js");
    const colors = [];
    const re = /"([^"]*)"/g;
    let m;
    while ((m = re.exec(match[1])) !== null) colors.push(m[1]);
    if (colors.length !== 30) throw new Error("Expected 30 palette entries, found " + colors.length);
    return colors;
}

function px(n) {
    return n === 0 ? "0px" : n + "px";
}

function build() {
    const palette = loadPalette();
    const hit = ".show_hit_marker .hit_marker";
    const crit = ".show_crit_hit_marker .hit_marker";
    const out = [];
    const rule = (selector, declaration) => out.push(selector + " { " + declaration + " !important; }");
    const section = (title) => out.push("", "/* " + title + " */");

    out.push(
        "/* QOLLOCK feature: Custom Hit Marker.",
        " * GENERATED by scripts/generate_hit_marker_css.js. Edit the generator, not this file.",
        " * The ql_hit_marker manifest toggles one class per setting on the HUD root; each class",
        " * selects one rule below. Ranges and the palette come from the generator. */"
    );

    section("Length (normal hit)");
    for (let n = RANGES.length.min; n <= RANGES.length.max; n++) rule(".qol-hm-len-" + n + " " + hit, "width: " + px(n));

    section("Color (normal hit)");
    palette.forEach((color, i) => rule(".qol-hm-col-" + i + " " + hit, "background-color: " + (i === 0 ? NATIVE_HIT_COLOR : color)));

    section("Thickness (normal hit and crit)");
    for (let n = RANGES.thickness.min; n <= RANGES.thickness.max; n++) {
        out.push(".qol-hm-th-" + n + " " + hit + ", .qol-hm-th-" + n + " " + crit + " { height: " + px(n) + " !important; }");
    }

    section("Spacing from the crosshair center (all four arms)");
    for (let n = RANGES.offset.min; n <= RANGES.offset.max; n++) {
        for (const c of CORNERS) {
            const tx = (c.x < 0 ? "-" : "") + px(n);
            const ty = (c.y < 0 ? "-" : "") + px(n);
            rule(".qol-hm-off-" + n + " #" + c.id + ".hit_marker",
                "transform: rotateZ(" + c.angle + "deg) translateX(" + tx + ") translateY(" + ty + ")");
        }
    }

    section("Outline shadow (normal hit)");
    rule(".qol-hm-shadow " + hit, "box-shadow: " + OUTLINE_SHADOW);

    // Crit rules come after the hit rules so they win if both state classes are ever present.
    section("Length (crit)");
    for (let n = RANGES.length.min; n <= RANGES.length.max; n++) rule(".qol-hm-clen-" + n + " " + crit, "width: " + px(n));

    section("Color (crit)");
    palette.forEach((color, i) => rule(".qol-hm-ccol-" + i + " " + crit, "background-color: " + (i === 0 ? NATIVE_CRIT_COLOR : color)));

    section("Crit glow and outline shadow");
    rule(".qol-hm " + crit, "box-shadow: " + NATIVE_CRIT_GLOW);
    rule(".qol-hm-noglow " + crit, "box-shadow: 0px 0px 0px #00000000");
    rule(".qol-hm-noglow.qol-hm-shadow " + crit, "box-shadow: " + OUTLINE_SHADOW);

    return out.join("\n") + "\n";
}

function main() {
    const css = build();
    if (process.argv.includes("--check")) {
        const current = fs.existsSync(OUT) ? fs.readFileSync(OUT, "utf8") : "";
        if (current !== css) {
            console.error("ql_feat_hit_marker.css is out of date. Run: node scripts/generate_hit_marker_css.js");
            process.exit(1);
        }
        console.log("ql_feat_hit_marker.css is up to date.");
        return;
    }
    fs.writeFileSync(OUT, css);
    console.log("Wrote " + path.relative(process.cwd(), OUT) + " (" + css.length + " bytes).");
}

if (require.main === module) main();
module.exports = { build, RANGES };
